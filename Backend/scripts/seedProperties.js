async function seed() {
  const uri = process.env.MONGODB_URI;
  if (!uri) {
    console.error('❌ MONGODB_URI not found in Backend/.env');
    process.exit(1);
  }

  console.log('Connecting to MongoDB Atlas...');
  await mongoose.connect(uri);
  console.log('✅ Connected successfully!');

  const existingCount = await Property.countDocuments();
  console.log(`Current properties in database: ${existingCount}`);

  let inserted = 0;
  for (const item of dummyProperties) {
    const exists = await Property.findOne({ title: item.title });
    if (!exists) {
      await Property.create(item);
      inserted++;
      console.log(` + Added: "${item.title}" [${item.city} | ${item.price} | ${item.approvalStatus}]`);
    } else {
      console.log(` = Already exists: "${item.title}"`);
    }
  }

  const finalCount = await Property.countDocuments();
  console.log(`\n🎉 Seeding complete! Added ${inserted} new properties. Total properties in database: ${finalCount}`);

  await mongoose.disconnect();
}

seed().catch((err) => {
  console.error('Seeding error:', err.message);
  process.exit(1);
});
